/**
 * Deterministically pick an Unsplash portrait set based on the candidate's seed string and gender.
 */
export function getDatingCandidatePhotoSet(
  gender?: string | null,
  seedKey?: string | null
): CandidatePhotoSet {
  const pool =
    gender === "MALE"
      ? MALE_DATING_PHOTOS
      : FEMALE_DATING_PHOTOS;

  const key = seedKey || "candidate";
  let hash = 0;
  for (let i = 0; i < key.length; i++) {
    hash = (hash << 5) - hash + key.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % pool.length;
  return pool[index];
}
